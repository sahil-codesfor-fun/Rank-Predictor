'use client';

import React from 'react';
import { PreferenceItem } from '@/lib/predictor/types';
import {
  X,
  ListOrdered,
  ArrowUp,
  ArrowDown,
  Trash2,
  Copy,
  Download,
  Building2,
  Check,
} from 'lucide-react';
import { toast } from 'sonner';

interface PreferenceListDrawerProps {
  isOpen: boolean;
  onClose: () => void;
  items: PreferenceItem[];
  onReorder: (newItems: PreferenceItem[]) => void;
  onRemove: (id: string) => void;
  onClear: () => void;
}

export function PreferenceListDrawer({
  isOpen,
  onClose,
  items,
  onReorder,
  onRemove,
  onClear,
}: PreferenceListDrawerProps) {
  if (!isOpen) return null;

  const moveItem = (index: number, direction: 'up' | 'down') => {
    if (direction === 'up' && index === 0) return;
    if (direction === 'down' && index === items.length - 1) return;

    const newIndex = direction === 'up' ? index - 1 : index + 1;
    const cloned = [...items];
    const temp = cloned[index];
    cloned[index] = cloned[newIndex];
    cloned[newIndex] = temp;
    onReorder(cloned);
  };

  const handleCopyClipboard = () => {
    if (items.length === 0) {
      toast.error('Preference list is empty.');
      return;
    }

    const textContent = items
      .map(
        (it, idx) =>
          `Choice #${idx + 1}: ${it.institute} | Branch: ${it.branch} | Quota: ${it.quota} | Closing Rank: ~${it.closingRank}`
      )
      .join('\n');

    navigator.clipboard.writeText(textContent);
    toast.success('Formatted Preference List copied to clipboard!');
  };

  const handleDownloadTxt = () => {
    if (items.length === 0) {
      toast.error('Preference list is empty.');
      return;
    }

    const header = `=====================================================\nJOSAA / CSAB / MCC COUNSELING CHOICE FILLING ORDER\nGenerated by Standalone Rank & College Predictor 2027\n=====================================================\n\n`;
    const body = items
      .map(
        (it, idx) =>
          `Preference ${idx + 1}:\n  Institute: ${it.institute}\n  Program/Branch: ${it.branch}\n  Seat Quota: ${it.quota}\n  Historical Cutoff: ~${it.closingRank}\n  NIRF: #${it.nirfRank} | Avg CTC: ${it.avgPackage}\n`
      )
      .join('\n-----------------------------------------------------\n');

    const fullText = header + body;
    const blob = new Blob([fullText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `counseling_preferences_${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('Exported choices to .txt file successfully!');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm animate-fade-in">
      <div className="relative w-full max-w-3xl max-h-[90vh] bg-white dark:bg-slate-900 rounded-3xl p-6 sm:p-8 shadow-2xl border border-slate-200 dark:border-slate-800 flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-200 dark:border-slate-800">
          <div className="flex items-center gap-2.5">
            <div className="h-10 w-10 rounded-2xl bg-indigo-600 flex items-center justify-center text-white">
              <ListOrdered className="h-5 w-5" />
            </div>
            <div>
              <h3 className="text-lg font-black text-slate-900 dark:text-white">
                Counselling Preference List Builder
              </h3>
              <p className="text-xs text-slate-500">
                Arrange and export your dream choices for JoSAA, CSAB, MCC, or DU CSAS choice filling.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-slate-700 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Action Bar */}
        <div className="flex flex-wrap items-center justify-between gap-2 py-3 border-b border-slate-100 dark:border-slate-800">
          <span className="text-xs font-bold text-slate-600 dark:text-slate-300">
            Total Choices Added: {items.length}
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyClipboard}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-200 hover:bg-slate-200 dark:hover:bg-slate-700 transition"
            >
              <Copy className="h-3.5 w-3.5" />
              <span>Copy List</span>
            </button>
            <button
              onClick={handleDownloadTxt}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-bold bg-indigo-600 hover:bg-indigo-700 text-white shadow-xs transition"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Download .txt</span>
            </button>
            {items.length > 0 && (
              <button
                onClick={onClear}
                className="px-2.5 py-1.5 rounded-xl text-xs text-rose-600 hover:bg-rose-50 dark:hover:bg-rose-950/40 transition"
              >
                Clear All
              </button>
            )}
          </div>
        </div>

        {/* Reorderable List */}
        <div className="flex-1 overflow-y-auto py-4 space-y-2.5 pr-1">
          {items.length > 0 ? (
            items.map((item, idx) => (
              <div
                key={item.id}
                className="p-3.5 rounded-2xl bg-slate-50 dark:bg-slate-800/60 border border-slate-200/80 dark:border-slate-700/80 flex items-center justify-between gap-3 hover:border-indigo-300 transition"
              >
                <div className="flex items-center gap-3">
                  <div className="h-7 w-7 rounded-lg bg-indigo-600/10 text-indigo-700 dark:text-indigo-300 dark:bg-indigo-900/40 font-black text-xs flex items-center justify-center shrink-0">
                    #{idx + 1}
                  </div>
                  <div>
                    <h5 className="text-xs font-bold text-slate-900 dark:text-white leading-tight">
                      {item.institute}
                    </h5>
                    <p className="text-[11px] text-slate-500 flex items-center gap-2 mt-0.5">
                      <span>{item.branch}</span>
                      <span>•</span>
                      <span className="font-semibold text-slate-700 dark:text-slate-300">Quota: {item.quota}</span>
                      <span>•</span>
                      <span>CR ~{item.closingRank}</span>
                    </p>
                  </div>
                </div>

                {/* Reorder & Delete Buttons */}
                <div className="flex items-center gap-1 shrink-0">
                  <button
                    disabled={idx === 0}
                    onClick={() => moveItem(idx, 'up')}
                    className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 hover:text-indigo-600 hover:border-indigo-400 disabled:opacity-30 disabled:hover:border-slate-200 transition"
                    title="Move Choice Up"
                  >
                    <ArrowUp className="h-3.5 w-3.5" />
                  </button>
                  <button
                    disabled={idx === items.length - 1}
                    onClick={() => moveItem(idx, 'down')}
                    className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 hover:text-indigo-600 hover:border-indigo-400 disabled:opacity-30 disabled:hover:border-slate-200 transition"
                    title="Move Choice Down"
                  >
                    <ArrowDown className="h-3.5 w-3.5" />
                  </button>
                  <button
                    onClick={() => onRemove(item.id)}
                    className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 text-rose-500 hover:bg-rose-50 dark:hover:bg-rose-950/40 transition ml-1"
                    title="Remove from Preference List"
                  >
                    <Trash2 className="h-3.5 w-3.5" />
                  </button>
                </div>
              </div>
            ))
          ) : (
            <div className="text-center py-12 text-slate-400 text-xs">
              <Building2 className="h-10 w-10 mx-auto mb-2 opacity-40 text-slate-400" />
              <p className="font-semibold text-slate-600 dark:text-slate-400">
                Your preference list is empty.
              </p>
              <p className="text-[11px] text-slate-400 mt-1">
                Browse predicted colleges and click "Add to Preference List" to organize your choices.
              </p>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="pt-4 border-t border-slate-200 dark:border-slate-800 flex justify-end">
          <button
            onClick={onClose}
            className="px-5 py-2.5 rounded-xl text-xs font-bold bg-slate-900 dark:bg-white text-white dark:text-slate-900 hover:opacity-90 transition"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
}

